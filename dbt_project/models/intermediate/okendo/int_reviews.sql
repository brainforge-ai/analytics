SELECT
    REVIEWID as review_id,
    DATECREATED as date_created,
    CUSTOMERID as customer_id,
    SUBSCRIBERID as subscriber_id,
    PRODUCTID as product_id,
    PRODUCTNAME as product_name,
    VARIANTID as variant_id,
    VARIANTNAME as variant_name,
    RATING as rating,
    BODY as review_body,
    TITLE as review_title,
    REPLY as reply,
    COALESCE(reviewer:SOCIALCONNECTION::string, 'okendo') as review_source,
    REVIEWER:DISPLAYNAME::string as reviewer_display_name,
    REVIEWER:EMAIL::string as reviewer_email,
    REVIEWER:ISVERIFIED::boolean as reviewer_is_verified,
    REVIEWER:NAME::string as reviewer_name,
    REVIEWER:VERIFIEDSTATUS::string as reviewer_verified_status,
    ATTRIBUTESWITHRATING as attributes_with_rating,
    PRODUCTATTRIBUTES as product_attributes,
    MEDIA as media  ,
    _ORDER:ORDERID::varchar as order_id,
    _ORDER:ORDERNUMBER::varchar as order_number,
    HELPFULCOUNT as helpful_count,
    UNHELPFULCOUNT as unhelpful_count,
    ISRECOMMENDED as is_recommended,
    CONTAINSPROFANITY as contains_profanity,
    REWARD:COUPON:VALUE::float as reward_coupon_value,
    REWARD:COUPON:VALUETYPE::string as reward_coupon_value_type,
    REWARD:DESCRIPTION::string as reward_description,
    REWARD:INTEGRATION::string as reward_integration,
    REWARD:ISCOUPONUPGRADE::boolean as reward_is_coupon_upgrade,
    REWARD:TYPE::string as reward_type,
    REWARD:VALUE::string as reward_value,
    SENTIMENT as sentiment,
    STATUS as status,
    TAGS as tags
FROM {{ source('portable_okendo', 'reviews') }}
